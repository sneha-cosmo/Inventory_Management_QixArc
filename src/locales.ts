export function tText(text: string, lang: Language): string {
  if (lang !== 'ta') return text;
  
  const clean = text.trim().toLowerCase();
  
  // Try exact match or phrase match
  if (clean in TAMIL_PHRASES) {
    return TAMIL_PHRASES[clean];
  }

  // Fallback lookups for dynamic strings containing standard keywords:
  for (const [enKey, taVal] of Object.entries(TAMIL_PHRASES)) {
    if (clean === enKey) return taVal;
  }

  return text;
}

